#!/usr/bin/env node
/**
 * update-crawlers.mjs: refreshes assets/crawlers-list.mjs, the vendored
 * snapshot of the ai.robots.txt list of AI crawlers that assets/crawlers.mjs
 * matches user agents against. Part of the sectionsight skill (MIT).
 *
 *   node update-crawlers.mjs                    fetch robots.json at the newest commit that changed it
 *   node update-crawlers.mjs --from robots.json --commit <sha> --date YYYY-MM-DD
 *                                               use a downloaded copy (say which commit it is)
 *   node update-crawlers.mjs --out <file>       write elsewhere (default: ../assets/crawlers-list.mjs)
 *   node update-crawlers.mjs --check            print what would change, write nothing
 *
 * Source: https://github.com/ai-robots-txt/ai.robots.txt (robots.json, MIT).
 * Each entry keeps its name, a short operator name and a purpose class:
 *   live      fetched live for an answer (an assistant fetching a page a user asked about)
 *   agent     an agent acting for a user (a browser agent, a coding agent)
 *   search    indexing for an AI search engine
 *   training  collecting data to train models or build datasets
 *   other     anything else, or unclear
 * The class comes from the list's own "function" text and the name (see
 * purposeOf); review the diff before committing a refresh.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const REPO = 'ai-robots-txt/ai.robots.txt';
const rawUrl = (ref) => `https://raw.githubusercontent.com/${REPO}/${ref}/robots.json`;
const SOURCE = rawUrl('main');
const args = process.argv.slice(2);
const flag = (name) => {
  const i = args.indexOf(`--${name}`);
  return i < 0 ? undefined : args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : 'yes';
};

/** The purpose class of one entry of robots.json. */
export function purposeOf(name, fn) {
  const f = String(fn ?? '');
  if (/^AI Assistants$/i.test(f) || /-User(\/|$)/.test(name) || /user-initiated|user prompts|answers? to user|user queries|on behalf of/i.test(f)) return 'live';
  if (/AI Agents|Coding Agents/i.test(f)) return 'agent';
  if (/\bsearch\b/i.test(f)) return 'search';
  if (/train|LLM|scrap|dataset|machine learning|language model|AI model|data provider|data collection|AI products/i.test(f)) return 'training';
  return 'other';
}

/** A short operator name: markdown links unwrapped, the first clause, 40 characters. */
export function operatorOf(op) {
  let s = String(op ?? '').replace(/\[([^\]]*)\]\([^)]*\)/g, '$1').replace(/https?:\/\/\S+/g, '').trim();
  if (/^(unclear|unknown)/i.test(s)) return '';
  s = s.split(/,| that | to | used | which | - /)[0].trim();
  return s.length > 40 ? s.slice(0, 39).trim() + '…' : s;
}

/**
 * The compact list: one entry per name (both spellings of a name the list
 * gives in two cases are kept: user agents are matched case-sensitively); a
 * versioned duplicate ("MistralAI-User/1.0", "Brightbot 1.0") is dropped
 * when its base name is listed.
 */
export function compact(json) {
  const all = Object.entries(json).filter(([name]) => typeof name === 'string' && name.trim());
  const lower = new Set(all.map(([n]) => n.toLowerCase()));
  const seen = new Set();
  const out = [];
  for (const [name, v] of all) {
    const base = name.toLowerCase().replace(/(\/|\s)[\d.]+$/, '');
    if (base !== name.toLowerCase() && lower.has(base)) continue;
    if (seen.has(name)) continue;
    seen.add(name);
    out.push({ name, operator: operatorOf(v?.operator), purpose: purposeOf(name, v?.function) });
  }
  return out.sort((a, b) => a.name.localeCompare(b.name, 'en'));
}

export function render(list, { date, commit = '', source = commit ? rawUrl(commit) : SOURCE }) {
  return `/**
 * AI crawlers and fetchers: a vendored snapshot of the ai.robots.txt list,
 * generated by scripts/update-crawlers.mjs. Do not edit by hand; run the
 * script and review the diff.
 *
 * Source: ${source}
 * (https://github.com/ai-robots-txt/ai.robots.txt, MIT)
 * Snapshot: ${date}${commit ? `, upstream commit ${commit}` : ''}
 *
 * purpose: live (fetched live for an answer), agent (acts for a user),
 * search (AI search index), training (training data, datasets), other.
 */
export const CRAWLERS_SNAPSHOT = { date: '${date}', commit: '${commit}', source: '${source}' };
export const CRAWLERS = [
${list.map((x) => `  ${JSON.stringify(x)},`).join('\n')}
];
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const from = flag('from');
  const out = flag('out') ?? fileURLToPath(new URL('../assets/crawlers-list.mjs', import.meta.url));
  let json;
  let date;
  let commit = flag('commit') && flag('commit') !== 'yes' ? flag('commit') : '';
  if (from && from !== 'yes') {
    json = JSON.parse(readFileSync(from, 'utf8'));
    date = flag('date') && flag('date') !== 'yes' ? flag('date') : new Date().toISOString().slice(0, 10);
  } else {
    // The newest commit that changed robots.json, so the file names exactly what it holds.
    const api = await fetch(`https://api.github.com/repos/${REPO}/commits?path=robots.json&per_page=1`, { headers: { accept: 'application/vnd.github+json' } });
    const last = api.ok ? (await api.json())?.[0] : null;
    commit = typeof last?.sha === 'string' ? last.sha : '';
    if (!commit) {
      console.error(`could not read the newest commit of robots.json (${api.status}); pass --from and --commit`);
      process.exit(1);
    }
    const res = await fetch(rawUrl(commit));
    if (!res.ok) {
      console.error(`${rawUrl(commit)}: ${res.status}`);
      process.exit(1);
    }
    json = await res.json();
    date = String(last.commit?.committer?.date ?? new Date().toISOString()).slice(0, 10);
  }
  if (!json || typeof json !== 'object' || Array.isArray(json)) {
    console.error('robots.json is not an object of crawler entries');
    process.exit(1);
  }
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) {
    console.error('--date must be YYYY-MM-DD');
    process.exit(1);
  }
  if (commit && !/^[0-9a-f]{7,40}$/.test(commit)) {
    console.error('--commit must be a commit hash');
    process.exit(1);
  }
  const list = compact(json);
  const text = render(list, { date, commit });
  let before = '';
  try {
    before = readFileSync(out, 'utf8');
  } catch {}
  const names = (t) => new Set([...t.matchAll(/"name":"([^"]+)"/g)].map((m) => m[1]));
  const was = names(before);
  const now = names(text);
  const added = [...now].filter((n) => !was.has(n));
  const removed = [...was].filter((n) => !now.has(n));
  console.log(`${list.length} crawlers; added: ${added.join(', ') || 'none'}; removed: ${removed.join(', ') || 'none'}`);
  if (flag('check') !== 'yes') writeFileSync(out, text);
}
