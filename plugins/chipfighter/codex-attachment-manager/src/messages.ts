export type MessageKey = keyof typeof zh;
export const MESSAGES: Record<Lang, Record<MessageKey, string>> = { zh, en };

export function say(lang: Lang, key: MessageKey, vars: Record<string, string | number> = {}): string {
  return MESSAGES[lang][key].replace(/\{(\w+)\}/g, (all, name: string) => (name in vars ? String(vars[name]) : all));
}
